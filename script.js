const roadmapDatabase = Object.entries(careerRoadmaps).map(([field, career]) => ({
    field,
    aliases: [
        field,
        ...(career.careers || []),
        ...(career.aliases || [])
    ].map(alias => normalizeCareerField(alias))
}));

function normalizeCareerField(value) {
    return String(value || '')
        .trim()
        .toLowerCase()
        .replace(/[/&+]/g, ' ')
        .replace(/[^a-z0-9\s]/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
}

function resolveCareerRecord(field) {
    if (!field) {
        return null;
    }

    const normalizedField = normalizeCareerField(field);

    for (const record of roadmapDatabase) {
        if (record.aliases.includes(normalizedField)) {
            return careerRoadmaps[record.field] || null;
        }
    }

    return careerRoadmaps[field] || null;
}

// Language management
let currentLanguage = 'en'; // Default to English

function getDetailedRoadmap(field, level) {
    const career = resolveCareerRecord(field) || { roadmap: [] };
    const phases = [...career.roadmap];

    if (level === "Beginner") {
        return phases.slice(0, 3);
    }

    if (level === "Intermediate") {
        return phases.slice(0, 4);
    }

    return phases;
}

function getTextByLanguage(phase, key) {
    if (currentLanguage === 'hi') {
        return phase[key + 'Hi'] || phase[key];
    } else if (currentLanguage === 'hinglish') {
        return phase[key + 'Hinglish'] || phase[key];
    }
    return phase[key];
}

function getSummaryByLanguage(career) {
    if (currentLanguage === 'hi') {
        return career.summaryHi || career.summary;
    } else if (currentLanguage === 'hinglish') {
        return career.summaryHinglish || career.summary;
    }
    return career.summary;
}

// Helper function to check if section has meaningful content (not "N/A")
function hasRelevantContent(content) {
    if (!content || content.length === 0) return false;
    if (Array.isArray(content)) {
        return content.some(item => item && !item.includes("N/A") && item.trim() !== "");
    }
    return content && !content.includes("N/A") && content.trim() !== "";
}

function createDetailSection(title, emoji, content) {
    if (!hasRelevantContent(content)) return "";

    const contentHTML = Array.isArray(content)
        ? content.map(item => "<li>" + item + "</li>").join("")
        : "<li>" + content + "</li>";

    return "<div class='details-section'>" +
        "<h4>" + emoji + " " + title + "</h4>" +
        "<ul>" + contentHTML + "</ul>" +
        "</div>";
}

function buildPhaseDetailSections(phase) {
    const language = getTextByLanguage(phase, 'language');
    const dsa = getTextByLanguage(phase, 'dsa');
    const oops = getTextByLanguage(phase, 'oops');
    const database = getTextByLanguage(phase, 'database');
    const tools = getTextByLanguage(phase, 'tools');
    const projects = getTextByLanguage(phase, 'projects');

    const sections = [
        { title: currentLanguage === 'hi' ? 'भाषा' : 'Language', emoji: '💻', content: language },
        { title: currentLanguage === 'hi' ? 'बुनियादी कोडिंग' : 'Basic coding', emoji: '📊', content: dsa },
        { title: currentLanguage === 'hi' ? 'OOP Ideas' : 'OOP ideas', emoji: '🎯', content: oops },
        { title: currentLanguage === 'hi' ? 'डेटाबेस' : 'Database', emoji: '🗄️', content: database },
        { title: currentLanguage === 'hi' ? 'Tools' : 'Tools', emoji: '🛠️', content: tools },
        { title: currentLanguage === 'hi' ? 'Project ideas' : 'Project ideas', emoji: '🚀', content: projects }
    ];

    return sections.map(section => createDetailSection(section.title, section.emoji, section.content)).join("");
}

function getCareerSuggestions(field) {
    const career = resolveCareerRecord(field) || { careers: [] };
    return career.careers || [];
}

